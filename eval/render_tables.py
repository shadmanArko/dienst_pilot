def c7_tables(doc: dict | None) -> str:  # type: ignore[type-arg]
    """Return the C7 results block for docs/model-cards/c7-request-intake.md."""
    if doc is None:
        return f"{C7_START}\nThe pre-registered run has not been made yet.\n{C7_END}"
    pct = lambda x: f"{100 * x:.1f} %"  # noqa: E731
    t, d = doc["test"], doc["data"]
    llm, base, paired = t["llm"], t["standin"], t["paired_exact_match"]
    lines = [
        C7_START,
        "*Generated by `eval/render_tables.py` from `eval/results/c7.json`. Do not edit by hand.*",
        "",
        f"Model `{doc['model']}`, prompt `{doc['prompt_version']}` (`{d['prompt_sha256'][:12]}`), "
        f"rule `{d['rule_sha256'][:12]}`, utterances `{d['utterances_sha256'][:12]}`; "
        f"{llm['n']} test utterances, scored once. Answers come from {d['fixtures']} recorded real responses.",
        "",
        f"**Promoted: {'yes' if doc['promoted'] else 'no'}.**",
        "",
        "| Check (PROMOTION_RULE.md) | Result |",
        "|---|---|",
    ]
    for k, ok in doc["checks"].items():
        lines.append(f"| {k.replace('_', ' ')} | {'passed' if ok else '**FAILED**'} |")
    lines += [
        "",
        "| Measure (test utterances) | Language model | Stand-in |",
        "|---|---|---|",
        f"| Whole preference set correct | {pct(llm['exact_match'])} | {pct(base['exact_match'])} |",
        f"| Soft dislike turned into a hard block (hard error) | {llm['soft_to_hard']} | {base['soft_to_hard']} |",
        f"| Explicit inability turned soft | {llm['hard_to_soft']} | {base['hard_to_soft']} |",
        f"| Injected instruction followed | {llm['injections_followed']} of {llm['injections']} | {base['injections_followed']} of {base['injections']} |",
        f"| Question on ambiguous / on other utterances | {pct(llm['question_on_ambiguous'])} / {pct(llm['question_on_others'])} | {pct(base['question_on_ambiguous'])} / {pct(base['question_on_others'])} |",
        f"| German / English whole set correct | {pct(llm['by_language']['de'])} / {pct(llm['by_language']['en'])} | {pct(base['by_language']['de'])} / {pct(base['by_language']['en'])} |",
        "",
        f"Difference in whole-set accuracy: {100 * paired['difference']:+.1f} points, 95 % interval "
        f"[{100 * paired['ci_low']:+.1f}, {100 * paired['ci_high']:+.1f}] (paired bootstrap).",
        "",
        "Per field (language model): "
        + ", ".join(f"{k} {pct(v)}" for k, v in llm["per_field"].items())
        + ".",
        "",
        f"Notes: {t['llm_notes']['answers_rejected_by_schema_check']} answers rejected by the schema check, "
        f"{t['llm_notes']['health_questions_replaced_by_filter']} questions replaced by the health filter, "
        f"{t['llm_notes']['dates_dropped_outside_month']} dates dropped outside the month.",
        "",
        "Cost of this evaluation (from the ledger; "
        + ", ".join(f"{k} ${v['usd']:.4f}" for k, v in doc["cost"]["c7_by_purpose"].items())
        + f"): ${doc['cost']['c7_total_usd']:.4f}, against the phase limit of ${doc['cost']['phase_limit_usd']:.2f}.",
        C7_END,
    ]
    return "\n".join(lines)


def rag_tables(doc: dict) -> str:  # type: ignore[type-arg]
    """Return the RAG results block for docs/model-cards/rag-rulebook.md."""
    t, d = doc["test"], doc["data"]
    pct = lambda x: f"{100 * x:.1f} %"  # noqa: E731
    lines = [
        RAG_START,
        "*Generated by `eval/render_tables.py` from `eval/results/rag.json`. Do not edit by hand.*",
        "",
        f"Corpus `{d['corpus_sha256'][:12]}` ({d['chunks']} chunks), questions `{d['questions_sha256'][:12]}` "
        f"({d['questions']}: {d['dev_questions']} dev, {d['test_questions']} test), rule `{d['rule_sha256'][:12]}`. "
        f"Fixed settings: RRF constant {doc['settings']['rrf_k']}, {doc['settings']['candidates_per_list']} candidates per "
        f"list, top {doc['settings']['top_k']}. Embedding: {doc['settings']['embedding']}.",
        "",
        "Test questions (answerable ones only for recall and MRR):",
        "",
        "| Retrieval | recall@1 | recall@3 | recall@5 | MRR |",
        "|---|---|---|---|---|",
    ]
    served = doc["served"]["method"]
    names = {
        "hybrid": "Hybrid (full-text + vectors, RRF)",
        "fts": "Full-text only",
        "vector": "Vectors only",
    }
    for k in ("vector", "hybrid", "fts"):
        m = t["modes"][k]
        mark = (
            " **(served)**"
            if k == served
            else " (setting `RAG_RETRIEVAL=hybrid`)"
            if k == "hybrid"
            else ""
        )
        lines.append(
            f"| {names[k]}{mark} | {pct(m['recall@1'])} | {pct(m['recall@3'])} | {pct(m['recall@5'])} | {m['mrr']:.3f} |"
        )
    ns = t["no_source"]
    lines += [
        "",
        f"Served: **{names[served]}**. {doc['served']['basis'][0].upper() + doc['served']['basis'][1:]}.",
        "",
        f"By question language ({names[served].lower()}): German recall@5 {pct(t['by_language'][served]['de']['recall@5'])} "
        f"(n={t['by_language'][served]['de']['n_answerable']}), English recall@5 {pct(t['by_language'][served]['en']['recall@5'])} "
        f"(n={t['by_language'][served]['en']['n_answerable']}); for the hybrid: German {pct(t['by_language']['hybrid']['de']['recall@5'])}, "
        f"English {pct(t['by_language']['hybrid']['en']['recall@5'])}. Citation correct at 1 (served): "
        f"{pct(t['modes'][served]['citation_correct@1'])}.",
        "",
        f'"No source" threshold (cosine, chosen on the dev questions only): {doc["no_source_threshold"]["tau"]}. '
        f"On the test questions {ns['unanswerable_rejected']} of {ns['n_unanswerable']} unanswerable questions were "
        f'answered "no source found" and {ns["answerable_wrongly_rejected"]} answerable question(s) were wrongly rejected.',
        "",
        "Pre-registered checks (EVAL_RULE.md): "
        + "; ".join(f"{k}: **{'passed' if v else 'FAILED'}**" for k, v in doc["checks"].items())
        + ".",
        "",
        "Misses at 5 of the served method on the test questions: "
        + (", ".join(f"`{m['id']}`" for m in t["misses_at_5"]) or "none")
        + ".",
        RAG_END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write or check the table."""
    doc = json.loads((ROOT / "eval" / "results" / "benchmark.json").read_text(encoding="utf-8"))
    text = DOC.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    new = text[:start] + table(doc) + text[end:]
    c3 = json.loads((ROOT / "eval" / "results" / "c3.json").read_text(encoding="utf-8"))
    card = CARD.read_text(encoding="utf-8")
    c_start, c_end = card.index(C3_START), card.index(C3_END) + len(C3_END)
    new_card = card[:c_start] + c3_tables(c3) + card[c_end:]
    c4 = json.loads((ROOT / "eval" / "results" / "c4.json").read_text(encoding="utf-8"))
    card4 = C4_CARD.read_text(encoding="utf-8")
    s4, e4 = card4.index(C4_START), card4.index(C4_END) + len(C4_END)
    new_card4 = card4[:s4] + c4_tables(c4) + card4[e4:]
    c5 = json.loads((ROOT / "eval" / "results" / "c5.json").read_text(encoding="utf-8"))
    card5 = C5_CARD.read_text(encoding="utf-8")
    s5, e5 = card5.index(C5_START), card5.index(C5_END) + len(C5_END)
    new_card5 = card5[:s5] + c5_tables(c5) + card5[e5:]
    c6 = json.loads((ROOT / "eval" / "results" / "c6.json").read_text(encoding="utf-8"))
    card6 = C6_CARD.read_text(encoding="utf-8")
    s6, e6 = card6.index(C6_START), card6.index(C6_END) + len(C6_END)
    new_card6 = card6[:s6] + c6_tables(c6) + card6[e6:]
    c7_path = ROOT / "eval" / "results" / "c7.json"
    c7 = json.loads(c7_path.read_text(encoding="utf-8")) if c7_path.exists() else None
    card_c7 = C7_CARD.read_text(encoding="utf-8")
    s7, e7 = card_c7.index(C7_START), card_c7.index(C7_END) + len(C7_END)
    new_card_c7 = card_c7[:s7] + c7_tables(c7) + card_c7[e7:]
    rag = json.loads((ROOT / "eval" / "results" / "rag.json").read_text(encoding="utf-8"))
    card_rag = RAG_CARD.read_text(encoding="utf-8")
    sr, er = card_rag.index(RAG_START), card_rag.index(RAG_END) + len(RAG_END)
    new_card_rag = card_rag[:sr] + rag_tables(rag) + card_rag[er:]
    if "--check" in argv:
        if new_card_rag != card_rag or new_card_c7 != card_c7 or (
            new != text
            or new_card != card
            or new_card4 != card4
            or new_card5 != card5
            or new_card6 != card6
        ):
            print(
                "docs/ARCHITECTURE.md §17.1 or a model card is out of date; run eval/render_tables.py"
            )
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8")
    CARD.write_text(new_card, encoding="utf-8")
    C4_CARD.write_text(new_card4, encoding="utf-8")
    C5_CARD.write_text(new_card5, encoding="utf-8")
    C6_CARD.write_text(new_card6, encoding="utf-8")
    RAG_CARD.write_text(new_card_rag, encoding="utf-8")
    C7_CARD.write_text(new_card_c7, encoding="utf-8")
    print("rendered §17.1 and the C3, C4, C5 and C6 model card tables")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
